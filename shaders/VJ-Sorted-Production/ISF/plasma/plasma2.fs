#define time ((useFrameIndex ? (float(FRAMEINDEX) / fps) : TIME) * timeScale)
#define mouse vec2(mouseX, mouseY)
#define resolution RENDERSIZE
#ifdef GL_ES
precision mediump float;
#endif

//by @juju2143
void main( void ) {

	vec2 position = ( gl_FragCoord.xy / resolution.xy ) / 4.0;

	vec3 color = vec3(abs(sin(position.x*50.+position.y*20.-(time/2.) )), abs(sin(position.y*30.-(time/2.) )), abs(sin(position.x*20.+position.y*50.-(time/2.) )) );

	gl_FragColor = vec4(color, max(color.r, max(color.g, color.b)));
}
