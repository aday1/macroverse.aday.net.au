#define time ((useFrameIndex ? (float(FRAMEINDEX) / fps) : TIME) * timeScale)
#define mouse vec2(mouseX, mouseY)
#define resolution RENDERSIZE
// co3moz

#ifdef GL_ES
precision mediump float;
#endif

void main() {
	vec2 position = (gl_FragCoord.xy / resolution.xy);
	float c = sign(sin(distance(position * tan(position.y), vec2(0.5 - cos(time)/10., 0.5 + sin(time)/10.))*(50. + sin(time)*5.)));
	gl_FragColor = vec4(c > 0. ? vec3(c) : vec3(0.3333, 0.73333, abs(cos(time))), 1.0);
}
