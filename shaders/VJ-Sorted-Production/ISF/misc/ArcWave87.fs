#define time ((useFrameIndex ? (float(FRAMEINDEX) / fps) : TIME) * timeScale)
#define mouse vec2(mouseX, mouseY)
#define resolution RENDERSIZE
#ifdef GL_ES
precision mediump float;
#endif

void main( void ) 
{

	vec2 p = ( gl_FragCoord.xy / resolution.xy )-0.5;
	float c = 0.0;
	float a=atan(p.x,p.x)*10.*p.x;
	float d=4./length(-p);
	c=(atan(cos(d - a + time * 12.0 )*20.)*15./pow((d),1.15));
	gl_FragColor = vec4( vec3(121.,1.5, 8)*vec3( c*c*c, c*c-c, c*c*c/(1.-c) ), 1.0 );

}
