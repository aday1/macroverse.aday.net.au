#define time ((useFrameIndex ? (float(FRAMEINDEX) / fps) : TIME) * speed)
#define mouse vec2(mouseX, mouseY)
#define resolution (RENDERSIZE / zoom)
#ifdef GL_ES
precision mediump float;
#endif

#extension GL_OES_standard_derivatives : enable

varying vec2 surfacePosition; 

vec4 tex( vec2 g )
{
	vec2 p = g, a; vec4 f = vec4(9.);
    
    for(int x=-3;x<=3;x++)
    for(int y=-3;y<=3;y++)
        p = vec2(x,y),
       	a = sin( time*3.5 + 9. * fract(sin((floor(g)+p)*mat2(2,5,5,2)))),
        p += .5 + .5 * a - fract(g),
        f = min(f, length(p+p * cos(a.x*1.5)));
    
    return sqrt(0.5-vec4(10,10,1,1)*f);
}

vec4 tex2( vec2 g )
{
    g /= 4.;
    float color = sign((mod(g.x, 0.1) - 0.05) * (mod(g.y, 0.1) - 0.05));
    
    return sqrt(vec4(color));
}

void _userMain()
{
    vec2 uv = surfacePosition * 2.5;
    
    float t = time * 0.7;
    uv.y += 0.0;//sin(t) * .5;
    uv.x += 0.0;//cos(t) * .5;
    float a = atan(uv.x,uv.y)/1.57;
    float d = max(max(abs(uv.x),abs(uv.y)), min(abs(uv.x)+uv.y, length(uv)));
   
    vec2 k = vec2(a,.8/d + t);
    
    vec4 tx = tex(k*6.);
    vec4 tx2 = tex2(k*2.);
    
    // ground
    gl_FragColor = tx2;
    
    // wall
    if (d<=abs(uv.x)+0.05||d<=abs(uv.x)+uv.y)
        gl_FragColor = tx;
    
    gl_FragColor *= d;
	gl_FragColor.a = 1.;
	
}

void main() {
    _userMain();
    vec3 c = gl_FragColor.rgb;
    float a = gl_FragColor.a;
    float luma = dot(c, vec3(0.299, 0.587, 0.114));
    c = mix(vec3(luma), c, saturation);
    c = (c - 0.5) * contrast + 0.5;
    c *= vec3(colorR, colorG, colorB);
    c += brightness;
    if (hueShift > 0.001) {
        float cosH = cos(hueShift * 6.28318);
        float sinH = sin(hueShift * 6.28318);
        c = vec3(
            c.r * (0.299 + 0.701*cosH + 0.168*sinH) + c.g * (0.587 - 0.587*cosH + 0.330*sinH) + c.b * (0.114 - 0.114*cosH - 0.497*sinH),
            c.r * (0.299 - 0.299*cosH - 0.328*sinH) + c.g * (0.587 + 0.413*cosH + 0.035*sinH) + c.b * (0.114 - 0.114*cosH + 0.292*sinH),
            c.r * (0.299 - 0.300*cosH + 1.250*sinH) + c.g * (0.587 - 0.588*cosH - 1.050*sinH) + c.b * (0.114 + 0.886*cosH - 0.203*sinH)
        );
    }
    if (invert) c = 1.0 - c;
    gl_FragColor = vec4(clamp(c, 0.0, 1.0), a);
}