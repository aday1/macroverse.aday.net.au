#define time ((useFrameIndex ? (float(FRAMEINDEX) / fps) : TIME) * speed)
#define mouse vec2(mouseX, mouseY)
#define resolution (RENDERSIZE / zoom)
#ifdef GL_ES
precision mediump float;
#endif

// Posted by Trisomie21

#define LAYERS 3.0

float rand(vec2 co){ return fract(sin(dot(co.xy ,vec2(12.9898,78.233))) * 43758.5453); }

void _userMain( void ) {
	
	float count = 4.0;
	vec3 color = vec3(0.0);
	
	vec2 pos = gl_FragCoord.xy - resolution.xy*.5;
	float dist = length(pos) / resolution.y;
	vec2 c = vec2(dist, atan(pos.x, pos.y) / (3.1416*2.0));
	
	for (float i = 0.0; i < LAYERS; ++i)
	{
		float t = time*(1.0+i*i);
		
		vec2 uv = c*(i+1.0);
		
		vec2 p = uv;
		
		p.x = pow(uv.x, .1) - (t*.01);
		p.y /= 2.0;
		
		float r = pow(uv.x, .1) - (t*.01);
		
		uv.x = mod(r, 0.01)/.01;
		uv.y = mod(uv.y, 0.02)/.02;
		
		float a = 1.0-length(uv*2.0-1.0)/2.0;
	
		vec3 m = fract(r*200.0 * vec3(.5, 1.0, -.25)*0.5)+i*.2;
		
		p = floor(p*100.0);
		float d = (rand(p)-0.8)*10.0;
		d = clamp(d*dist, 0.0, 8.0);
	
		color = max(color, a*m*d);
	}

	gl_FragColor =  vec4(color, max(color.r, max(color.g, color.b)) );
}

void main() {
    _userMain();
    vec3 c = gl_FragColor.rgb;
    float a = gl_FragColor.a;
    float luma = dot(c, vec3(0.299, 0.587, 0.114));
    c = mix(vec3(luma), c, saturation);
    c = (c - 0.5) * contrast + 0.5;
    c *= vec3(colorR, colorG, colorB);
    c += brightness;
    if (hueShift > 0.001) {
        float cosH = cos(hueShift * 6.28318);
        float sinH = sin(hueShift * 6.28318);
        c = vec3(
            c.r * (0.299 + 0.701*cosH + 0.168*sinH) + c.g * (0.587 - 0.587*cosH + 0.330*sinH) + c.b * (0.114 - 0.114*cosH - 0.497*sinH),
            c.r * (0.299 - 0.299*cosH - 0.328*sinH) + c.g * (0.587 + 0.413*cosH + 0.035*sinH) + c.b * (0.114 - 0.114*cosH + 0.292*sinH),
            c.r * (0.299 - 0.300*cosH + 1.250*sinH) + c.g * (0.587 - 0.588*cosH - 1.050*sinH) + c.b * (0.114 + 0.886*cosH - 0.203*sinH)
        );
    }
    if (invert) c = 1.0 - c;
    gl_FragColor = vec4(clamp(c, 0.0, 1.0), a);
}