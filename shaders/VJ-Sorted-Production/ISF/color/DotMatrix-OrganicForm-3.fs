#define time ((useFrameIndex ? (float(FRAMEINDEX) / fps) : TIME) * speed)
#define mouse vec2(mouseX, mouseY)
#define resolution (RENDERSIZE / zoom)
#ifdef GL_ES
precision mediump float;
#endif

/* original: http://glslsandbox.com/e#5891 */

const float Tau		= 6.2832;
const float Speed	= .04;
const float Density	= 0.1;
const float Shape	= .03;

float random( vec2 seed ) {
	return fract(sin(seed.x+seed.y*1e3)*1e5);
}

float Cell(vec2 coord) {
	vec2 cell = fract(coord) * vec2(.5,2.) - vec2(.0,.5);
	return (1.-length(cell*2.-1.))*step(random(floor(coord)),Density)*2.;
}

void _userMain( void ) {
	vec2 position = mouse / 2.0;

	float px = gl_FragCoord.x / resolution.x - 0.8 +position.x;+ (sin(time) * 0.1);
    float py = gl_FragCoord.y / resolution.y - 0.8 + position.y+(cos(time) * 0.1);
    vec2 p = vec2(px, py);
	
	float a = fract(atan(px, py) / Tau);
	float d = sqrt(px*px + py*py);
	
	vec2 coord = vec2(pow(d, Shape), a)*256.;
	vec2 delta = vec2(-time*Speed*256., .5);
	
	float c = 0.;
	for(int i=0; i<4; i++) {
		coord += delta;
		c = max(c, Cell(coord));
	}
	
    float f = c*d - length(p) + 0.8;
	gl_FragColor = vec4(0., f, f, 1.0);
}

void main() {
    _userMain();
    vec3 c = gl_FragColor.rgb;
    float a = gl_FragColor.a;
    float luma = dot(c, vec3(0.299, 0.587, 0.114));
    c = mix(vec3(luma), c, saturation);
    c = (c - 0.5) * contrast + 0.5;
    c *= vec3(colorR, colorG, colorB);
    c += brightness;
    if (hueShift > 0.001) {
        float cosH = cos(hueShift * 6.28318);
        float sinH = sin(hueShift * 6.28318);
        c = vec3(
            c.r * (0.299 + 0.701*cosH + 0.168*sinH) + c.g * (0.587 - 0.587*cosH + 0.330*sinH) + c.b * (0.114 - 0.114*cosH - 0.497*sinH),
            c.r * (0.299 - 0.299*cosH - 0.328*sinH) + c.g * (0.587 + 0.413*cosH + 0.035*sinH) + c.b * (0.114 - 0.114*cosH + 0.292*sinH),
            c.r * (0.299 - 0.300*cosH + 1.250*sinH) + c.g * (0.587 - 0.588*cosH - 1.050*sinH) + c.b * (0.114 + 0.886*cosH - 0.203*sinH)
        );
    }
    if (invert) c = 1.0 - c;
    gl_FragColor = vec4(clamp(c, 0.0, 1.0), a);
}